export const CATEGORIES = [...new Set(QUESTIONS.map((q) => q.category))]

function shuffle(array) {
  const copy = [...array]
  for (let i = copy.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1))
    ;[copy[i], copy[j]] = [copy[j], copy[i]]
  }
  return copy
}

/** `count` unique questions from the whole pool, no repeats within the returned set. */
export function pickUnique(count, pool = QUESTIONS) {
  return shuffle(pool).slice(0, count)
}

/** `count` unique questions, prioritizing `category` first and filling the rest at random. */
export function pickForCategory(category, count, pool = QUESTIONS) {
  const inCategory = shuffle(pool.filter((q) => q.category === category))
  const rest = shuffle(pool.filter((q) => q.category !== category))
  return [...inCategory, ...rest].slice(0, count)
}
